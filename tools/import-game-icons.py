#!/usr/bin/env python3
"""Builds the picture icons for bash covers and scene kits from game-icons.net.

The icons are by game-icons.net's artists (Lorc, Delapouite and others) under
Creative Commons BY 3.0; the credits are on the Licenses page
(live-relay/legal/licenses.html) and under the icon picker.

tools/game-icons.json lists the chosen icons: our id (the first ones keep the
ids of the app's original tabletop icons, so saved bashes and kits switch to
the new art), name, picker category, the game-icons.net file name and artist.

Usage, from the repo root:
  git clone --depth 1 https://github.com/game-icons/icons.git /tmp/game-icons
  python3 tools/import-game-icons.py /tmp/game-icons
  python3 tools/generate-ios-icons.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / 'tools/game-icons.json'
OUT = ROOT / 'soundboard-mac/src/renderer/game-icons.js'

# How each artist folder is credited (license.txt in the game-icons repo).
ARTISTS = {
    'lorc': 'Lorc', 'delapouite': 'Delapouite', 'skoll': 'Skoll', 'sbed': 'Sbed', 'willdabeast': 'Willdabeast',
    'caro-asercion': 'Caro Asercion', 'darkzaitzev': 'DarkZaitzev', 'carl-olsen': 'Carl Olsen', 'faithtoken': 'Faithtoken',
    'cathelineau': 'Cathelineau', 'john-redman': 'John Redman', 'lucasms': 'Lucas', 'zajkonur': 'Zajkonur',
}


def main():
    src = Path(sys.argv[1])
    icons = json.loads(MANIFEST.read_text())
    rows = []
    for icon in icons:
        svg = (src / icon['author'] / f"{icon['gi']}.svg").read_text()
        paths = [d for d in re.findall(r'<path[^>]*\sd="([^"]+)"', svg) if d.strip() != 'M0 0h512v512H0z']
        d = ' '.join(paths)
        rows.append([icon['id'], icon['name'], icon['category'], ARTISTS[icon['author']], d])
    used = sorted({r[3] for r in rows})
    lines = [
        '// Generated by tools/import-game-icons.py. Do not edit by hand.',
        '// Picture icons for bash covers and scene kits, from game-icons.net,',
        f"// by {', '.join(used)}. Creative Commons BY 3.0 (https://creativecommons.org/licenses/by/3.0/).",
        '// Each: [id, name, category, artist, SVG path on a 512×512 grid].',
        '// eslint-disable-next-line no-unused-vars',
        'const GameIcons = [',
    ]
    for r in rows:
        lines.append('  ' + json.dumps(r, ensure_ascii=False) + ',')
    lines += ['];', "if (typeof module !== 'undefined' && module.exports) module.exports = GameIcons;", '']
    OUT.write_text('\n'.join(lines))
    print(f'Wrote {len(rows)} icons to {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
